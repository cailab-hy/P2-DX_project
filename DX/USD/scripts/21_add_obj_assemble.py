# every horizontal face at the top (z_top) and at the underside / body-top level (z_bot) is re-triangulated around the holes
# (the 1.082 m level would otherwise close the holes 3 cm below the top; some v3 faces are wound downward: sign ignored)
levels = {}
for zl, up in ((z_top, True), (z_bot, False)):
    sel = (np.abs(V[F][:, :, 2] - zl) < 1e-3).all(1)
    if sel.any():
        levels[zl] = (sel, up)
in_level = np.zeros(len(F), bool)
for sel, _ in levels.values():
    in_level |= sel
for i, f in enumerate(F):
    if not in_level[i]:
        groups.setdefault(mat_of.get(i, top_mat), []).append(len(faces))
        faces.append(list(f))
n_tri = 0
for zl, (sel, up) in levels.items():
    region = unary_union([Polygon(V[f, :2]).buffer(1e-5) for f in F[sel]]).buffer(-1e-5).difference(hole_u)
    mat_l = mat_of.get(int(np.where(sel)[0][0]), top_mat)
    for t in shapely.constrained_delaunay_triangles(region).geoms:
        c_ = np.asarray(t.exterior.coords)[:3]
        d1, d2 = c_[1] - c_[0], c_[2] - c_[0]
        if (d1[0] * d2[1] - d1[1] * d2[0] < 0) == up:
            c_ = c_[::-1]
        n0 = len(verts)
        verts += [[c_[k][0], c_[k][1], zl] for k in range(3)]
        groups.setdefault(mat_l if not up else top_mat, []).append(len(faces))
        faces.append([n0, n0 + 1, n0 + 2])
        n_tri += 1
