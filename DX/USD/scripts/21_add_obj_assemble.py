def v3path(p):
    return str(p).replace("/DX_Hub_Building", B, 1)


def label(prim, cls):
    UsdSemantics.LabelsAPI.Apply(prim, "class").CreateLabelsAttr().Set([cls])


def collider_box(name, x, y, z, cls):
    c = UsdGeom.Cube.Define(stage, f"{B}/Collision/{name}")
    c.CreateSizeAttr(1.0)
    xf = UsdGeom.Xformable(c)
    xf.AddTranslateOp().Set(Gf.Vec3d((x[0] + x[1]) / 2, (y[0] + y[1]) / 2, (z[0] + z[1]) / 2))
    xf.AddScaleOp().Set(Gf.Vec3f(x[1] - x[0], y[1] - y[0], z[1] - z[0]))
    c.CreatePurposeAttr(UsdGeom.Tokens.guide)
    UsdPhysics.CollisionAPI.Apply(c.GetPrim())
    label(c.GetPrim(), cls)


def box_faces(x, y, z):
    (x0, x1), (y0, y1), (z0, z1) = x, y, z
    P = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0), (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    return P, [[0, 3, 2, 1], [4, 5, 6, 7], [0, 1, 5, 4], [1, 2, 6, 5], [2, 3, 7, 6], [3, 0, 4, 7]]


def write_mesh(path, V, faces, groups, cls, src=None):
    """faces: list of index lists; groups: {material path: [face ids]} -> GeomSubsets."""
    me = UsdGeom.Mesh.Define(stage, path)
    me.CreatePointsAttr(Vt.Vec3fArray([Gf.Vec3f(*map(float, p)) for p in V]))
    me.CreateFaceVertexCountsAttr([len(f) for f in faces])
    me.CreateFaceVertexIndicesAttr([int(i) for f in faces for i in f])
    me.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
    V_ = np.asarray(V, float)
    me.CreateExtentAttr(Vt.Vec3fArray([Gf.Vec3f(*V_.min(0)), Gf.Vec3f(*V_.max(0))]))
    api = UsdShade.MaterialBindingAPI.Apply(me.GetPrim())
    for k, (mat, ids) in enumerate(groups.items()):
        sub = api.CreateMaterialBindSubset(f"finish_{k}", Vt.IntArray(sorted(ids)))
        UsdShade.MaterialBindingAPI.Apply(sub.GetPrim()).Bind(UsdShade.Material(stage.GetPrimAtPath(mat)))
    label(me.GetPrim(), cls)
    return me


