        verts += [[ax, ay, z_bot], [bx, by, z_bot], [bx, by, z_top], [ax, ay, z_top]]
        groups.setdefault(top_mat, []).append(len(faces))
        faces.append([n0, n0 + 1, n0 + 2, n0 + 3])
