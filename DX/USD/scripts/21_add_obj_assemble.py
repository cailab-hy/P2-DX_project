def make_logo(sg, path):
    """Wall lettering after photos logo.jpg / logo2.jpg, three rows on shared centre lines (user 2026-10-16):
      top     partner logos (white icons + names), all icons one height, icons and names centred on one line, evenly spaced
      middle  CARE + 3-line caption: CARE ink height (cap top -> baseline) = caption block (line-1 ink top -> line-3 baseline);
              the pair is centred horizontally
      bottom  경기테크노파크 (colour icon, left edge) and 한양대학교 ERICA (colour emblem, right edge) on one centre line,
              same icon height and text size
    Numbers in config signage.layout_px are pixels of the 690 x 500 block measured on the photo."""
    import numpy as np_
    from PIL import Image, ImageDraw, ImageFilter, ImageFont
    L = sg["layout_px"]
    ppm = 2000                                                        # texture pixels per metre
    Wp, Hp = int(sg["size"][0] * ppm), int(sg["size"][1] * ppm)
    s = min(Wp / L["w"], Hp / L["h"])
    ox, oy = (Wp - L["w"] * s) / 2, (Hp - L["h"] * s) / 2
    X = lambda v: ox + v * s                                          # noqa: E731  block px -> texture px
    Y = lambda v: oy + v * s                                          # noqa: E731
    col = {k: tuple(v) + (255,) for k, v in sg["colors_rgb"].items()}
    fonts = {"black": "/usr/share/fonts/opentype/noto/NotoSansCJK-Black.ttc", "bold": "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc",
             "medium": "/usr/share/fonts/opentype/noto/NotoSansCJK-Medium.ttc"}
    src = DST / "assets" / "Signage" / "sources"
    im = Image.new("RGBA", (Wp, Hp), (0, 0, 0, 0))
    white_layer = Image.new("RGBA", (Wp, Hp), (0, 0, 0, 0))            # white parts get a soft shadow (white acrylic on a light wall)
    dr = ImageDraw.Draw(im)

    def F(kind, size):
        return ImageFont.truetype(fonts[kind], max(4, int(size)), index=1)

    def ink(text, f, anchor="ls"):                                    # ink box relative to the anchor point
        return dr.textbbox((0, 0), text, font=f, anchor=anchor)

    def text_at(layer, text, f, colour, x, cy=None, baseline=None):
        """Ink left edge at x; vertically either ink centred on cy or baseline at the given y."""
        l_, t_, r_, b_ = ink(text, f)
        yb = baseline if baseline is not None else cy - (t_ + b_) / 2
        ImageDraw.Draw(layer).text((x - l_, yb), text, font=f, fill=colour, anchor="ls")
        return r_ - l_

    def icon_img(fname, white, h, max_w):
        g = Image.open(src / fname).convert("RGBA")
        a = np_.asarray(g).astype(np_.float32)
        if (a[..., 3] > 250).all():                                     # no alpha: key out the white background
            ink_ = (255 - a[..., :3].min(axis=2))
            a[..., 3] = np_.clip((ink_ - 25) * 4, 0, 255)
        if white:
            a[..., :3] = np_.array(sg["colors_rgb"]["white"], np_.float32)
        g = Image.fromarray(a.astype(np_.uint8), "RGBA")
        g = g.crop(g.getbbox())
        k = min(h / g.height, max_w / g.width)
        return g.resize((max(1, int(g.width * k)), max(1, int(g.height * k))), Image.LANCZOS)

    def group(layer, item, f, colour, x, cy, icon_h, gap):            # icon then name, both centred on cy; returns width
        g = icon_img(item["icon"], item.get("white", False), icon_h, item.get("icon_max_w", 3 * icon_h / s) * s)
        layer.alpha_composite(g, (int(x), int(cy - g.height / 2)))
        return g.width + gap + text_at(layer, item["text"], f, colour, x + g.width + gap, cy=cy)

    def group_w(item, f, icon_h, gap):
        g = icon_img(item["icon"], item.get("white", False), icon_h, item.get("icon_max_w", 3 * icon_h / s) * s)
        l_, _, r_, _ = ink(item["text"], f)
        return g.width + gap + r_ - l_

    def size_for_ink_h(text, kind, h):                                # font size whose ink (cap top -> baseline) is h px tall
        lo, hi = 4, int(h * 3)
        while lo < hi:
            m = (lo + hi + 1) // 2
            lo, hi = (m, hi) if -ink(text, F(kind, m))[1] <= h else (lo, m - 1)
        return lo

    # ---- top row: partners
    T = L["top_row"]
    cy, ih, gap = Y(T["center_y"]), T["icon_h"] * s, T["gap"] * s
    fp = F("bold", size_for_ink_h("산업통상부", "bold", T["text_h"] * s))
    widths = [group_w(pt, fp, ih, gap) for pt in L["partners"]]
    x0, x1 = X(T["x0"]), X(T["x1"])
    between = (x1 - x0 - sum(widths)) / (len(widths) - 1)
    x = x0
    for pt, w_ in zip(L["partners"], widths):
        group(white_layer, pt, fp, col["white"], x, cy, ih, gap)
        x += w_ + between
    # ---- middle row: CARE + caption (caption size chosen so the pair fills middle_row.width)
    M = L["middle_row"]
    cap = sg["lines"]["care_caption"]

    def middle(cs):
        fc = F("medium", cs)
        pitch = cs * M["caption_leading"]
        top1 = -min(ink(cap[0], fc)[1], 0)                              # line-1 ink above its baseline
        span = top1 + (len(cap) - 1) * pitch                          # line-1 ink top -> last baseline
        fC = F("black", size_for_ink_h(sg["lines"]["care"], "black", span))
        l_, _, r_, _ = ink(sg["lines"]["care"], fC)
        cw = max(ink(t_, fc)[2] - ink(t_, fc)[0] for t_ in cap)
        return fc, fC, pitch, top1, span, r_ - l_, cw

    cs = 4
    while middle(cs + 1)[5] + M["gap"] * s + middle(cs + 1)[6] <= M["width"] * s:
        cs += 1
    fc, fC, pitch, top1, span, care_w, cap_w = middle(cs)
    xs = X(L["w"] / 2) - (care_w + M["gap"] * s + cap_w) / 2
    top = Y(M["center_y"]) - span / 2
    text_at(im, sg["lines"]["care"], fC, col["navy"], xs, baseline=top + span)
    for k, t_ in enumerate(cap):
        text_at(im, t_, fc, col["navy"], xs + care_w + M["gap"] * s, baseline=top + top1 + k * pitch)
    # ---- 로봇직업교육센터 (largest size inside its box, centred)
    K = L["korean"]
    fk = F("black", size_for_ink_h(sg["lines"]["korean"], "black", (K[3] - K[1]) * s))
    while ink(sg["lines"]["korean"], fk)[2] - ink(sg["lines"]["korean"], fk)[0] > (K[2] - K[0]) * s:
        fk = F("black", fk.size - 1)
    kl, kt, kr, kb = ink(sg["lines"]["korean"], fk)
    text_at(im, sg["lines"]["korean"], fk, col["navy"], X(L["w"] / 2) - (kr - kl) / 2, cy=Y((K[1] + K[3]) / 2))
    # ---- bottom row: 경기테크노파크 (left) and 한양대학교 ERICA (right) on one centre line
    Bt = L["bottom_row"]
    cy, ih, gap = Y(Bt["center_y"]), Bt["icon_h"] * s, Bt["gap"] * s
    tp, hy = dict(L["tp"], kind="black", colour="tp_text"), dict(L["hanyang"], kind="bold", colour="navy")
    th = Bt["text_h"] * s
    while True:                                                       # one text size; shrink until the two groups keep min_space
        ftp, fhy = F(tp["kind"], size_for_ink_h(tp["text"], tp["kind"], th)), F(hy["kind"], size_for_ink_h("한양대학교", hy["kind"], th))
        wtp, why = group_w(tp, ftp, ih, gap), group_w(hy, fhy, ih, gap)
        if wtp + why + Bt["min_space"] * s <= (Bt["x1"] - Bt["x0"]) * s or th < 10:
            break
        th *= 0.97
    group(im, tp, ftp, col[tp["colour"]], X(Bt["x0"]), cy, ih, gap)
    group(im, hy, fhy, col[hy["colour"]], X(Bt["x1"]) - why, cy, ih, gap)
    sh = Image.new("RGBA", (Wp, Hp), col["shadow"][:3] + (0,))        # soft drop shadow of the white partner row
    sh.putalpha(white_layer.getchannel("A").point(lambda v: int(v * 0.55)))
    sh = sh.filter(ImageFilter.GaussianBlur(4))
    out = Image.new("RGBA", (Wp, Hp), (0, 0, 0, 0))
    out.alpha_composite(sh, (5, 5))
    out.alpha_composite(white_layer)
    out.alpha_composite(im)
    path.parent.mkdir(parents=True, exist_ok=True)
    out.save(path)


